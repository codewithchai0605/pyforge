function inTable(
    table: ReadonlyArray<readonly [number, number]>,
    cp: number,
): boolean {
    let lo = 0;
    let hi = table.length - 1;
    while (lo <= hi) {
        const mid = (lo + hi) >> 1;
        const [from, to] = table[mid]!;
        if (cp < from) hi = mid - 1;
        else if (cp > to) lo = mid + 1;
        else return true;
    }
    return false;
}

export function charWidth(cp: number): 0 | 1 | 2 {
    if (cp === 0) return 0;
    if (cp < 32 || (cp >= 0x7f && cp < 0xa0)) return 0;
    if (cp < 0x300) return 1;
    if (inTable(ZERO, cp)) return 0;
    if (inTable(WIDE, cp)) return 2;
    return 1;
}

/** Width of a whole string, in cells. */
export function stringWidth(text: string): number {
    let w = 0;
    for (const ch of text) w += charWidth(ch.codePointAt(0)!);
    return w;
}